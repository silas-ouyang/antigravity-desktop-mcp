/**
 * 从 `backend/parts/*.ps1` 生成确定性的模块化入口 `backend/worker.ps1`。
 *
 * 为什么采用模块化 dot-source 入口 + 全量片段 SHA-256 清单，而不是单个 670KB 拼接脚本：
 *   1. 每个 `.ps1` 片段单独保持 ASCII + 无 BOM UTF-8 且由 Windows PowerShell 正常加载与检查，
 *      避免 670KB 单一大文件误触 Defender 静态脚本启发式拦截；
 *   2. 将所有 `parts/*.ps1` 的确定性 SHA-256 清单写入 `worker.ps1`，既保持逐字节可重现性，
 *      又使 `worker.ps1` 的自身哈希（`ready.info.build`）与全部片段版本严格绑定；
 *   3. 运行时按 ASCII 字典序依次 dot-source 加载，严格保持 `02-native-code.ps1` 先于 `02a-safety.ps1`。
 *
 * 用法：
 *   node scripts/build-worker.mjs          # 生成 backend/worker.ps1
 *   node scripts/build-worker.mjs --check  # 校验磁盘 worker.ps1 与当前 parts/*.ps1 清单完全一致
 */
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const WORKER = join(ROOT, 'backend', 'worker.ps1');
const PARTS_DIR = join(ROOT, 'backend', 'parts');
const CHECK_ONLY = process.argv.includes('--check');

function compareAscii(a, b) {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}

const partNames = readdirSync(PARTS_DIR).filter((name) => name.endsWith('.ps1')).sort(compareAscii);
if (partNames.length === 0) {
  console.error('backend/parts 里没有片段');
  process.exit(1);
}

const manifest = [];
for (const name of partNames) {
  const raw = readFileSync(join(PARTS_DIR, name));
  if (raw.length >= 3 && raw[0] === 0xef && raw[1] === 0xbb && raw[2] === 0xbf) {
    console.error(`片段 ${name} 包含 UTF-8 BOM：PowerShell 5.1 需要无 BOM 文件。`);
    process.exit(1);
  }
  if (raw.byteLength === 0) {
    console.error(`片段 ${name} 为空，已中止`);
    process.exit(1);
  }
  const sha256 = createHash('sha256').update(raw).digest('hex');
  manifest.push({ name, bytes: raw.byteLength, sha256 });
}

const partArrayLines = manifest
  .map((entry) => `  '${entry.name}' # bytes=${entry.bytes} sha256=${entry.sha256}`)
  .join('\n');

const generated = [
  '# DSH / Antigravity Desktop MCP backend worker entrypoint (deterministic modular loader).',
  '# Auto-generated by scripts/build-worker.mjs — do not edit manually.',
  '# Parts are loaded in explicit ASCII order so 02-native-code.ps1 initializes before 02a-safety.ps1.',
  '',
  '$ErrorActionPreference = \'Stop\'',
  '$ProgressPreference = \'SilentlyContinue\'',
  '',
  '$script:WorkerRootDir = Split-Path -Parent $PSCommandPath',
  '$script:WorkerPartsDir = Join-Path $script:WorkerRootDir \'parts\'',
  '$script:WorkerPartsManifest = @(',
  partArrayLines,
  ')',
  '',
  'foreach ($partName in $script:WorkerPartsManifest) {',
  '  $partPath = Join-Path $script:WorkerPartsDir $partName',
  '  if (-not (Test-Path -LiteralPath $partPath)) {',
  '    throw "Missing backend worker part: $partPath"',
  '  }',
  '  . $partPath',
  '}',
  '',
].join('\n');

const onDisk = existsSync(WORKER) ? readFileSync(WORKER, 'utf8') : '';
if (CHECK_ONLY) {
  if (onDisk === generated) {
    const totalBytes = manifest.reduce((sum, item) => sum + item.bytes, 0);
    console.log(`worker 构建检查 OK：${partNames.length} 个片段清单与 worker.ps1 一致（片段共 ${totalBytes} 字节）`);
    process.exit(0);
  }
  console.error('worker 构建检查失败：磁盘上的 backend/worker.ps1 与 backend/parts/*.ps1 清单不一致。');
  console.error('请运行 node scripts/build-worker.mjs 重新生成。');
  process.exit(1);
}

if (onDisk === generated) {
  console.log(`worker.ps1 已是最新（${partNames.length} 个片段清单），未改写`);
  process.exit(0);
}

writeFileSync(WORKER, generated, 'utf8');
const after = readFileSync(WORKER, 'utf8');
if (after !== generated) {
  console.error('写入后校验失败：磁盘内容与生成结果不一致');
  process.exit(1);
}
console.log(`已生成模块化 backend/worker.ps1：${partNames.length} 个片段（${Buffer.byteLength(generated)} 字节入口）`);
